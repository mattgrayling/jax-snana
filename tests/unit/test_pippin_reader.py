def _write(tmp_path, config: dict) -> Path:
    path = tmp_path / "config.yml"
    path.write_text(yaml.safe_dump(config))
    return path


def _sim(name="A", **keys):
    return {"IA": {"BASE": str(_SIM_INPUT), **keys}}


