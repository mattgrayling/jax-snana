def _by_name(stages):
    return {stage.name: stage for stage in stages}


def _fit(stages, fit, source):
    """The fits of one source by the LCFIT stage ``fit``."""
    return stages[fit].version(stages[source])


def test_a_real_pippin_config_builds_the_whole_chain(tmp_path):
    """Pippin's own create-cov test config, with a wfit section appended:
    every section that has a stage here becomes one, named as Pippin names
    the task, and joined as the config joins them."""
    text = (_PIPPIN / "valid_create_cov.yml").read_text()
    text += ("\nCOSMOFIT:\n  WFIT:\n    W:\n      OPTS:\n"
             "        WFITOPTS:\n          - /om_pri/ -ompri 0.31 -dompri 0.01\n")
    config = tmp_path / "config.yml"
    config.write_text(text)

    stages = _by_name(read(config, data_dirs=[_DATA_FILES]))

    assert isinstance(stages["DATADES3YR"], Data)
    assert stages["DATADES3YR"].directory == _DATA_FILES / "surveys"
    sim = stages["ASIM"]
    assert isinstance(sim, Sim)
    # three components, each generated by every one of the ten repeat jobs
    assert len(sim.input_files) == 30
    assert sim.input_files[0].name == "sn_ia_g10_sdss_3yr.input"
    # Pippin's FORMAT_MASK 48 has random CIDs, so every repeat job keeps the seed
    assert {o["RANSEED"] for o in sim.overrides} == {12345}
    assert sim.overrides[0]["FORMAT_MASK"] == 48
    assert sim.ngen_unit == 1.0
    assert "NGEN_UNIT" not in sim.overrides[0]
    assert sim.overrides[0]["SOLID_ANGLE"] == "10"
    assert isinstance(stages["LCFIT_D"], Fit)
    assert stages["LCFIT_D"].datasets == (stages["DATADES3YR"], sim)
    # the Perfect classifier classifies every fit; FitProb has no stage here
    assert isinstance(stages["PERFECT_D_DATADES3YR"], Classify)
    assert "FITPROBTEST_D_ASIM" not in stages
    bbc = stages["BCOR"]
    assert isinstance(bbc, BBC)
    assert bbc.data == (stages["PERFECT_D_DATADES3YR"],)
    assert bbc.biascor == (stages["PERFECT_D_ASIM"],)
    assert bbc.input_file == _DATA_FILES / "surveys" / "des" / "bbc" / "bbc_5yr.input"
    assert bbc.overrides == {"varname_pIa": "PROB_PERFECT", "blindflag": 2}
    covariance = stages["COVTEST"]
    assert isinstance(covariance, Covariance) and covariance.distances is bbc
    assert covariance.covopts == ["[NOSYS] [=DEFAULT,=DEFAULT]"]
    cosmology = stages["WFIT_W_om_pri"]
    assert isinstance(cosmology, Cosmology) and cosmology.covariance is covariance
    assert cosmology.covopts == ("ALL", "NOSYS")
    assert cosmology.overrides == {"ompri": 0.31, "dompri": 0.01, "blind_mode": "auto"}
    assert bbc.configuration().nzbin > 0
    assert covariance.configuration()[0].write_mask_cov & 8


